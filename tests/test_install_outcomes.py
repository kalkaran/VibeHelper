@pytest.mark.parametrize("provider", ["CodexHelper", "ClaudeHelper"])
@pytest.mark.parametrize("platform", ["MacOS", "WSL"])
def test_standalone_quality_phase_installs_runtime(tmp_path, provider, platform):
    fakebin = tmp_path / "bin"
    fakebin.mkdir()
    (fakebin / "python3").symlink_to(sys.executable)
    home = tmp_path / "home"
    home.mkdir()
    repo = tmp_path / "repo"
    repo.mkdir()
    env = dict(
        os.environ, HOME=str(home), PATH=str(fakebin) + os.pathsep + "/usr/bin:/bin"
    )
    result = invoke(
        "bash",
        str(ROOT / provider / platform / "part2.sh"),
        "--refresh-managed",
        cwd=repo,
        env=env,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    kind = provider.removesuffix("Helper").lower()
    for name in [
        "ai-quality-wrapper.py",
        "agent-check-edited.py",
        "agent-verify.sh",
        "quality-hook.py",
        "test-verification.py",
    ]:
        assert (repo / "vibe_scripts" / kind / name).read_bytes() == (
            ROOT / "templates/vibe_scripts" / name
        ).read_bytes()

    assert invoke("git", "init", "-q", cwd=repo).returncode == 0
    deleted = write(repo / "deleted.py", "before\n")
    runtime = repo / "vibe_scripts" / kind / "quality-hook.py"
    payload = json.dumps({"cwd": str(repo), "session_id": "installed-deletion"})
    for event in ("SessionStart", "Stop"):
        if event == "Stop":
            deleted.unlink()
        checked = subprocess.run(
            [sys.executable, str(runtime), "--provider", kind, "--event", event],
            cwd=repo,
            input=payload,
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        assert checked.returncode == 0, checked.stderr
        outcome = json.loads(checked.stdout)
        if event == "SessionStart":
            assert outcome == {}, checked.stderr
        elif outcome:
            assert outcome.get("decision") == "block", outcome
        else:
            # A deletion may pass only after real package checks, never an empty skip.
            evidence = sorted((repo / ".cache/quality-sessions/results").glob("*.json"))
            final = json.loads(evidence[-1].read_text())
            assert final["status"] == "passed" and final["command_count"] > 0, final
    assert "Tests were not run by this hook" in checked.stderr + checked.stdout


