def invoke(*args, cwd, env=None):
    return subprocess.run(
        args, cwd=cwd, env=env, capture_output=True, text=True, timeout=60, check=False
    )


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


